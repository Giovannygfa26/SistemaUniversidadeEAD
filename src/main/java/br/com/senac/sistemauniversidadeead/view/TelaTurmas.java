    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
   String codigo = txtCodTurma.getText().trim();
    String anoTexto = txtAno.getText().trim();
    String periodo = txtPeriodo.getText().trim();

    if (codigo.isEmpty()
            || anoTexto.isEmpty()
            || periodo.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    if (comboCurso.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione um curso.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    if (comboProfessor.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione um professor.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int ano;

    try {

        ano = Integer.parseInt(anoTexto);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "O ano deve ser um número.",
                "Valor inválido",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    String nomeCurso = (String) comboCurso.getSelectedItem();
    String nomeProfessor = (String) comboProfessor.getSelectedItem();

    Curso cursoSelecionado = null;
    Professor professorSelecionado = null;

    List<Curso> cursos = cursoDAO.listarCursos();

    for (Curso curso : cursos) {

        if (curso.getNome().equals(nomeCurso)) {
            cursoSelecionado = curso;
            break;
        }
    }

    List<Professor> professores = professorDAO.listarProfessores();

    for (Professor professor : professores) {

        if (professor.getNome().equals(nomeProfessor)) {
            professorSelecionado = professor;
            break;
        }
    }

    if (cursoSelecionado == null) {

        JOptionPane.showMessageDialog(
                this,
                "Curso selecionado não encontrado.",
                "Erro",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    if (professorSelecionado == null) {

        JOptionPane.showMessageDialog(
                this,
                "Professor selecionado não encontrado.",
                "Erro",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    Turma turma = new Turma();

    turma.setCodigo(codigo);
    turma.setAno(ano);
    turma.setPeriodo(periodo);
    turma.setCurso(cursoSelecionado);
    turma.setProfessor(professorSelecionado);

    turmaDAO.cadastrarTurma(turma);

    atualizarTabela();

    JOptionPane.showMessageDialog(
            this,
            "Turma cadastrada com sucesso!",
            "Sucesso",
            JOptionPane.INFORMATION_MESSAGE
    );

    limparCampos();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tbTurma.getSelectedRow();

    if (linha == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione uma turma para excluir.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir a turma selecionada?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION
    );

    if (resposta == JOptionPane.YES_OPTION) {

        int id = (int) tbTurma.getValueAt(linha, 0);

        turmaDAO.excluirTurma(id);

        atualizarTabela();

        JOptionPane.showMessageDialog(
                this,
                "Turma excluída com sucesso!",
                "Sucesso",
                JOptionPane.INFORMATION_MESSAGE
        );
    }
    }//GEN-LAST:event_btnExcluirActionPerformed

