private void carregarCursos() {

    comboCurso.removeAllItems();

    List<Curso> cursos = cursoDAO.listarCursos();

    for (Curso curso : cursos) {
        comboCurso.addItem(curso.getNome());
    }
}

private void carregarProfessores() {

    comboProfessor.removeAllItems();

    List<Professor> professores = professorDAO.listarProfessores();

    for (Professor professor : professores) {
        comboProfessor.addItem(professor.getNome());
    }
}

    private void limparCampos() {

    txtCodTurma.setText("");
    txtAno.setText("");
    txtPeriodo.setText("");

    if (comboCurso.getItemCount() > 0) {
        comboCurso.setSelectedIndex(0);
    }

    if (comboProfessor.getItemCount() > 0) {
        comboProfessor.setSelectedIndex(0);
    }

    txtCodTurma.requestFocus();
}
    
private void atualizarTabela() {

    DefaultTableModel modelo =
            (DefaultTableModel) tbTurma.getModel();

    modelo.setRowCount(0);

    List<Turma> turmas = turmaDAO.listarTurmas();

    for (Turma turma : turmas) {

        modelo.addRow(new Object[]{
            turma.getId(),
            turma.getCodigo(),
            turma.getPeriodo(),
            turma.getAno(),
            turma.getCurso().getNome(),
            turma.getProfessor().getNome()
        });
    }
}
