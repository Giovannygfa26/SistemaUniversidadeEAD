    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
   int linha = tbMatricula.getSelectedRow();

    if (linha == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione uma matrícula para excluir."
        );

        return;
    }

    int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir a matrícula selecionada?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION
    );

    if (resposta == JOptionPane.YES_OPTION) {

        int id = (int) tbMatricula.getValueAt(linha, 0);

        matriculaDAO.excluirMatricula(id);

        atualizarTabela();

        JOptionPane.showMessageDialog(
                this,
                "Matrícula excluída com sucesso!"
        );
    }
    }//GEN-LAST:event_btnExcluirActionPerformed

