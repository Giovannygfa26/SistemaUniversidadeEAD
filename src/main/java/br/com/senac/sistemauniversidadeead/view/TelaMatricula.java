  private void atualizarTabela() {

    DefaultTableModel modelo =
            (DefaultTableModel) tbMatricula.getModel();

    modelo.setRowCount(0);

    for (Matricula matricula : matriculaDAO.listarMatriculas()) {

        modelo.addRow(new Object[]{
            matricula.getId(),
            matricula.getNomeAluno(),
            matricula.getCpfAluno(),
            matricula.getData(),
            matricula.getTelefone()
        });
    }
}

