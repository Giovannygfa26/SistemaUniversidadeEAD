    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
       String nome = txtNome.getText().trim();
    String cpf = txtCPF.getText().trim();
    String dataTexto = txtData.getText().trim();
    String telefone = txtTel.getText().trim();

    if (nome.isEmpty()
            || cpf.isEmpty()
            || dataTexto.isEmpty()
            || telefone.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    LocalDate data;

    try {

        data = LocalDate.parse(dataTexto);

    } catch (DateTimeParseException e) {

        JOptionPane.showMessageDialog(
                this,
                "Data inválida.\nUse o formato AAAA-MM-DD.",
                "Data inválida",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    Matricula matricula = new Matricula();

    matricula.setNomeAluno(nome);
    matricula.setCpfAluno(cpf);
    matricula.setData(data);
    matricula.setTelefone(telefone);

    matriculaDAO.cadastrarMatricula(matricula);

    atualizarTabela();

    JOptionPane.showMessageDialog(
            this,
            "Matrícula cadastrada com sucesso!"
    );

    limparCampos();
    }//GEN-LAST:event_btnSalvarActionPerformed

